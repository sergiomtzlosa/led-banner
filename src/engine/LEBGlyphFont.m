#import "LEBGlyphFont.h"
#import <string.h>

#define LEB_GLYPH(ch, ...) \
    case ch: { \
        static const uint8_t pattern[7] = { __VA_ARGS__ }; \
        memcpy(rows, pattern, sizeof(pattern)); \
        return YES; \
    }

@implementation LEBGlyphFont

+ (NSUInteger)glyphWidth {
    return 5;
}

+ (NSUInteger)glyphHeight {
    return 7;
}

+ (NSUInteger)advance {
    return 6;
}

+ (BOOL)getRows:(uint8_t *)rows forCharacter:(unichar)character {
    unichar ch = character;
    if (ch >= 'a' && ch <= 'z') {
        ch = ch - ('a' - 'A');
    }

    if (ch == ' ') {
        memset(rows, 0, 7);
        return YES;
    }

    switch (ch) {
        LEB_GLYPH('A', 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11)
        LEB_GLYPH('B', 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E)
        LEB_GLYPH('C', 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E)
        LEB_GLYPH('D', 0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E)
        LEB_GLYPH('E', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F)
        LEB_GLYPH('F', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10)
        LEB_GLYPH('G', 0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F)
        LEB_GLYPH('H', 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11)
        LEB_GLYPH('I', 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E)
        LEB_GLYPH('J', 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C)
        LEB_GLYPH('K', 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11)
        LEB_GLYPH('L', 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F)
        LEB_GLYPH('M', 0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11)
        LEB_GLYPH('N', 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11)
        LEB_GLYPH('O', 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E)
        LEB_GLYPH('P', 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10)
        LEB_GLYPH('Q', 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D)
        LEB_GLYPH('R', 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11)
        LEB_GLYPH('S', 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E)
        LEB_GLYPH('T', 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04)
        LEB_GLYPH('U', 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E)
        LEB_GLYPH('V', 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04)
        LEB_GLYPH('W', 0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A)
        LEB_GLYPH('X', 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11)
        LEB_GLYPH('Y', 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04)
        LEB_GLYPH('Z', 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F)

        LEB_GLYPH('0', 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E)
        LEB_GLYPH('1', 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E)
        LEB_GLYPH('2', 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F)
        LEB_GLYPH('3', 0x0E, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0E)
        LEB_GLYPH('4', 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02)
        LEB_GLYPH('5', 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E)
        LEB_GLYPH('6', 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E)
        LEB_GLYPH('7', 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08)
        LEB_GLYPH('8', 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E)
        LEB_GLYPH('9', 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C)

        LEB_GLYPH('.', 0x00, 0x00, 0x00, 0x00, 0x00, 0x06, 0x06)
        LEB_GLYPH(',', 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x08)
        LEB_GLYPH('!', 0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04)
        LEB_GLYPH('?', 0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04)
        LEB_GLYPH('-', 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00)
        LEB_GLYPH('+', 0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00)
        LEB_GLYPH('=', 0x00, 0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00)
        LEB_GLYPH(':', 0x00, 0x04, 0x04, 0x00, 0x04, 0x04, 0x00)
        LEB_GLYPH(';', 0x00, 0x04, 0x04, 0x00, 0x04, 0x08, 0x00)
        LEB_GLYPH('/', 0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10)
        LEB_GLYPH('\\', 0x10, 0x08, 0x08, 0x04, 0x02, 0x02, 0x01)
        LEB_GLYPH('\'', 0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00)
        LEB_GLYPH('"', 0x0A, 0x0A, 0x00, 0x00, 0x00, 0x00, 0x00)
        LEB_GLYPH('(', 0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02)
        LEB_GLYPH(')', 0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08)
        LEB_GLYPH('%', 0x19, 0x1A, 0x04, 0x04, 0x08, 0x0B, 0x13)
        LEB_GLYPH('&', 0x0C, 0x12, 0x12, 0x0C, 0x15, 0x12, 0x0D)
        LEB_GLYPH('*', 0x00, 0x15, 0x0E, 0x1F, 0x0E, 0x15, 0x00)
        LEB_GLYPH('#', 0x0A, 0x0A, 0x1F, 0x0A, 0x1F, 0x0A, 0x0A)
        LEB_GLYPH('@', 0x0E, 0x11, 0x17, 0x15, 0x17, 0x10, 0x0F)
        LEB_GLYPH('<', 0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02)
        LEB_GLYPH('>', 0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08)
        LEB_GLYPH('_', 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1F)

        default:
            break;
    }

    static const uint8_t fallback[7] = { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04 };
    memcpy(rows, fallback, sizeof(fallback));
    return NO;
}

@end
